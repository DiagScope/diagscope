package dev.diagscope.cli;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.SerializationFeature;
import com.fasterxml.jackson.databind.node.ArrayNode;
import com.fasterxml.jackson.databind.node.ObjectNode;
import picocli.CommandLine.Command;
import picocli.CommandLine.Option;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.concurrent.Callable;
import java.util.regex.Pattern;

/**
 * Wires DiagScope into a coding assistant: instructions it reads at the start, and for Claude Code a Stop hook
 * that scans the files changed in the session before the assistant is allowed to finish.
 *
 * <p>The command only adds. Instructions live in a marked block that is replaced on re-run; the hook script is
 * regenerated; {@code .claude/settings.json} keeps everything it already had. A check at the end of the task is
 * deliberate: a scan costs 1 to 15 seconds regardless of how many files changed (see docs/PERFORMANCE.md), too
 * slow for every edit.</p>
 */
@Command(
        name = "init-agent",
        mixinStandardHelpOptions = true,
        description = "Set up coding-assistant instructions and an end-of-task DiagScope check."
)
public final class InitAgentCommand implements Callable<Integer> {
    enum Target { CLAUDE, AGENTS, ALL }

    static final String BEGIN = "<!-- diagscope:begin (generated by `diagscope init-agent`; edits inside are overwritten) -->";
    static final String END = "<!-- diagscope:end -->";
    static final String HOOK_PATH = ".claude/hooks/diagscope-stop.sh";
    static final String SETTINGS_PATH = ".claude/settings.json";
    private static final String HOOK_COMMAND = "\"$CLAUDE_PROJECT_DIR\"/" + HOOK_PATH;
    private static final Pattern SAFE_COMMAND = Pattern.compile("[A-Za-z0-9_./ :=@+-]+");
    private static final Pattern SAFE_PROFILE = Pattern.compile("[A-Za-z0-9_-]+");

    @Option(names = "--project", defaultValue = ".", description = "Project directory; default: current directory")
    private Path project;

    @Option(names = "--target", defaultValue = "ALL",
            description = "CLAUDE: CLAUDE.md, Stop hook and .claude/settings.json. AGENTS: AGENTS.md only"
                    + " (read by most other assistants). ALL: both. Default: ${DEFAULT-VALUE}")
    private Target target;

    @Option(names = "--command", defaultValue = "diagscope",
            description = "How the hook invokes DiagScope, e.g. \"java -jar /opt/diagscope.jar\". Default: ${DEFAULT-VALUE}")
    private String command;

    @Option(names = "--gate-profile",
            description = "Gate profile from diagscope.yml the hook uses. Without it the project gate applies,"
                    + " or --fail-on ERROR when diagscope.yml has none")
    private String gateProfile;

    @Option(names = "--dry-run", description = "Print what would change and write nothing")
    private boolean dryRun;

    @Override
    public Integer call() {
        try {
            if (!Files.isDirectory(project)) {
                throw new IllegalArgumentException("Project directory does not exist: " + project);
            }
            if (!SAFE_COMMAND.matcher(command).matches()) {
                throw new IllegalArgumentException("--command may only contain letters, digits, spaces and _./:=@+-");
            }
            if (gateProfile != null && !SAFE_PROFILE.matcher(gateProfile).matches()) {
                throw new IllegalArgumentException("--gate-profile may only contain letters, digits, _ and -");
            }
            Path root = project.toAbsolutePath().normalize();
            var report = new ArrayList<String>();
            boolean claude = target != Target.AGENTS;
            boolean agents = target != Target.CLAUDE;

            if (agents) upsertBlock(root, "AGENTS.md", instructions(false), report);
            if (claude) {
                upsertBlock(root, "CLAUDE.md", instructions(true), report);
                write(root, HOOK_PATH, hookScript(command, gateProfile), true, report);
                mergeSettings(root, report);
            }
            report.forEach(System.out::println);
            if (dryRun) System.out.println("Dry run: nothing was written.");
            return 0;
        } catch (IllegalArgumentException exception) {
            System.err.println("Invalid init-agent input: " + exception.getMessage());
            return 2;
        } catch (IOException exception) {
            System.err.println("DiagScope failed: " + exception.getMessage());
            return 2;
        }
    }

    static String instructions(boolean withHook) {
        return BEGIN + "\n## DiagScope\n\n"
                + "This project is checked with DiagScope, a static analyzer for diagnostic gaps: swallowed exceptions,"
                + " missing logs and metrics, transaction and resilience misuse.\n\n"
                + "- Before you declare a task done, run `diagscope scan --format AGENT --files <the files you changed>`"
                + " and fix what it reports, starting with ERROR.\n"
                + "- Fix the cause. Do not add `diagscope:ignore` comments, waivers, baseline entries or rule overrides"
                + " to make a finding disappear without asking the user.\n"
                + "- If you believe a finding is a false positive, tell the user the rule id and why; do not silence it.\n"
                + "- `diagscope explain <RULE_ID>` gives the reasoning and the source behind a rule.\n"
                + (withHook ? "- A Stop hook (`" + HOOK_PATH + "`) runs this check automatically when you finish and"
                        + " hands the findings back to you once.\n" : "")
                + END + "\n";
    }

    static String hookScript(String command, String gateProfile) {
        return """
                #!/usr/bin/env bash
                # Generated by `diagscope init-agent`. Scans the Java/Kotlin files changed in the working tree before the
                # assistant may stop. Exit 2 hands the findings back to the assistant; it runs once per stop, never loops.
                set -u
                cd "${CLAUDE_PROJECT_DIR:-.}" || exit 0
                input=$(cat)
                if printf '%s' "$input" | grep -Eq '"stop_hook_active"[[:space:]]*:[[:space:]]*true'; then exit 0; fi

                DIAGSCOPE="${DIAGSCOPE:-@COMMAND@}"
                files=""
                if git rev-parse --is-inside-work-tree >/dev/null 2>&1; then
                  files=$( { git diff --relative --name-only HEAD 2>/dev/null; git ls-files --others --exclude-standard; } \\
                    | grep -E '\\.(java|kt)$' | paste -sd, - )
                  [ -z "$files" ] && exit 0
                fi

                args=(scan --project . --format AGENT)
                [ -n "$files" ] && args+=(--files "$files")
                profile="${DIAGSCOPE_GATE_PROFILE:-@PROFILE@}"
                if [ -n "$profile" ]; then
                  args+=(--gate-profile "$profile")
                elif ! grep -qs '^gate:' diagscope.yml; then
                  args+=(--fail-on ERROR)
                fi

                # shellcheck disable=SC2086
                output=$($DIAGSCOPE "${args[@]}" 2>&1)
                status=$?
                if [ "$status" -eq 1 ]; then
                  printf '%s\\n' "$output" >&2
                  exit 2
                fi
                exit 0
                """.replace("@COMMAND@", command).replace("@PROFILE@", gateProfile == null ? "" : gateProfile);
    }

    /** Returns {@code existing} with the generated block replaced, or appended when absent. */
    static String withBlock(String existing, String block) {
        if (existing == null || existing.isBlank()) return block;
        int begin = existing.indexOf("<!-- diagscope:begin");
        int end = existing.indexOf(END);
        if (begin >= 0 && end > begin) {
            return existing.substring(0, begin) + block.stripTrailing()
                    + existing.substring(end + END.length());
        }
        return existing.stripTrailing() + "\n\n" + block;
    }

    private void upsertBlock(Path root, String name, String block, List<String> report) throws IOException {
        Path file = root.resolve(name);
        String existing = Files.isRegularFile(file) ? Files.readString(file, StandardCharsets.UTF_8) : null;
        write(root, name, withBlock(existing, block), false, report);
    }

    private void mergeSettings(Path root, List<String> report) throws IOException {
        var mapper = new ObjectMapper().enable(SerializationFeature.INDENT_OUTPUT);
        Path file = root.resolve(SETTINGS_PATH);
        ObjectNode settings = Files.isRegularFile(file)
                ? (ObjectNode) mapper.readTree(Files.readString(file, StandardCharsets.UTF_8))
                : mapper.createObjectNode();
        if (settings == null) settings = mapper.createObjectNode();
        ObjectNode hooks = settings.withObject("/hooks");
        ArrayNode stop = hooks.withArray("/Stop");
        boolean present = false;
        for (var group : stop) {
            for (var hook : group.path("hooks")) {
                if (hook.path("command").asText().contains("diagscope-stop.sh")) present = true;
            }
        }
        if (!present) {
            ObjectNode entry = stop.addObject();
            ObjectNode hook = entry.putArray("hooks").addObject();
            hook.put("type", "command");
            hook.put("command", HOOK_COMMAND);
        }
        write(root, SETTINGS_PATH, mapper.writeValueAsString(settings) + "\n", false, report);
    }

    private void write(Path root, String name, String content, boolean executable, List<String> report)
            throws IOException {
        Path file = root.resolve(name);
        boolean exists = Files.isRegularFile(file);
        if (exists && Files.readString(file, StandardCharsets.UTF_8).equals(content)) {
            report.add("unchanged  " + name);
            return;
        }
        report.add((dryRun ? "would " : "") + (exists ? "update     " : "create     ") + name);
        if (dryRun) return;
        if (file.getParent() != null) Files.createDirectories(file.getParent());
        Files.writeString(file, content, StandardCharsets.UTF_8);
        if (executable) file.toFile().setExecutable(true, false);
    }
}
